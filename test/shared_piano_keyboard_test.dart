import 'dart:convert';
import 'dart:io';
import 'package:flutter/material.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:provider/provider.dart';
import 'package:shared_preferences/shared_preferences.dart';
import 'package:sornaz/components/app_piano_keyboard.dart';
import 'package:sornaz/components/piano_keyboard_spec.dart';
import 'package:sornaz/screens/Notation/notation_piano_keyboard.dart';
import 'package:sornaz/screens/Tuner/controller/tuner_provider.dart';
import 'package:sornaz/screens/Tuner/ui/components/piano_keyboard.dart';
import 'social_widget_test.dart' as fixture;
import 'tuner_professional_playback_test.dart' show RecordingNotePlayer;

void main() {
  test('browser styles match the canonical piano spec', () {
    final expected =
        '// Generated by tools/sync_piano_keyboard.dart; edit PianoKeyboardSpec.\n'
        'globalThis.SornazPianoStyle=Object.freeze(${jsonEncode(PianoKeyboardSpec.browser)});\n';
    expect(File('assets/notation/piano_style.js').readAsStringSync(), expected);
  });
  testWidgets('tuner and notation use the same piano, colors and dimensions', (
    tester,
  ) async {
    SharedPreferences.setMockInitialValues({});
    final player = RecordingNotePlayer();
    final tuner = TunerProvider(notePlayer: player);
    tuner.keyboardSettings.showQuarterTones = true;
    tuner.keyboardSettings.startOctave = 4;
    tuner.keyboardSettings.octaveCount = 1;
    final events = <Map<String, Object>>[];
    await tester.pumpWidget(
      fixture.host(
        ChangeNotifierProvider<TunerProvider>.value(
          value: tuner,
          child: Scaffold(
            body: Column(
              children: [
                const PianoKeyboard(),
                NotationPianoKeyboard(
                  data: const {
                    'visible': true,
                    'enabled': true,
                    'quarterTones': true,
                    'labels': {'D4:k': 'D4'},
                  },
                  send: events.add,
                ),
              ],
            ),
          ),
        ),
      ),
    );
    await tester.pumpAndSettle();
    expect(find.byType(AppPianoKeyboard), findsNWidgets(2));
    final upper = tester.widget<Container>(
      find.byKey(const ValueKey('piano-C4:#')).first,
    );
    final lower = tester.widget<Container>(
      find.byKey(const ValueKey('piano-D4:b')).first,
    );
    expect(
      (lower.decoration as BoxDecoration).borderRadius,
      (upper.decoration as BoxDecoration).borderRadius,
    );
    final split = tester.widget<SizedBox>(
      find.byKey(const ValueKey('piano-black-C4')).first,
    );
    expect(split.child, isA<Column>());
    for (final entry in {
      'C4:': (60, 180.0),
      'C4:#': (40, 65.0),
      'D4:b': (40, 65.0),
      'D4:k': (40, 97.5),
      'C4:o': (40, 97.5),
    }.entries) {
      final keys = find.byKey(ValueKey('piano-${entry.key}'));
      expect(keys, findsNWidgets(2));
      expect(tester.getSize(keys.first), tester.getSize(keys.last));
      expect(tester.getSize(keys.first).height, entry.value.$2);
      expect(
        tester.getSize(keys.first).width,
        entry.key == 'C4:' ? 120 : entry.value.$1,
      );
      final first =
          tester.widget<Container>(keys.first).decoration! as BoxDecoration;
      final last =
          tester.widget<Container>(keys.last).decoration! as BoxDecoration;
      expect(first.color, last.color);
      if (entry.key == 'D4:k') {
        expect(first.color, const Color(PianoKeyboardSpec.koronColor));
      }
      if (entry.key == 'C4:o') {
        expect(first.color, const Color(PianoKeyboardSpec.soriColor));
      }
    }
    expect(
      tester.getSize(find.byKey(const ValueKey('piano-black-C4')).first),
      const Size(40, 130),
    );
    final whiteText = tester.widget<Text>(
      find
          .descendant(
            of: find.byKey(const ValueKey('piano-C4:')).first,
            matching: find.byType(Text),
          )
          .first,
    );
    final quarterText = tester.widget<Text>(
      find
          .descendant(
            of: find.byKey(const ValueKey('piano-D4:k')).first,
            matching: find.byType(Text),
          )
          .first,
    );
    expect(quarterText.style!.fontSize, whiteText.style!.fontSize);
    expect(const AppPianoKey(61, 'b').pitch, 'D4');
    expect(
      const AppPianoKey(61, 'b').frequency(),
      const AppPianoKey(61, '#').frequency(),
    );
    final key = find.byKey(const ValueKey('piano-D4:k')).last;
    await tester.tap(key);
    await tester.pump();
    expect(events.map((e) => e['phase']), ['down', 'up']);
    expect(events.first['pitch'], 'D4');
    expect(events.first['accidental'], 'k');
    events.clear();
    await tester.tap(find.byKey(const ValueKey('piano-D4:b')).last);
    await tester.pump();
    expect(events.first['pitch'], 'D4');
    expect(events.first['accidental'], 'b');
    events.clear();
    final gesture = await tester.startGesture(tester.getCenter(key));
    await gesture.moveBy(const Offset(30, 0));
    await gesture.up();
    await tester.pumpAndSettle();
    expect(events.map((e) => e['phase']), ['down', 'cancel']);
    expect(player.played, isEmpty);
    await tester.pumpWidget(const SizedBox());
    tuner.dispose();
  });
  testWidgets('western keys and disabled notation preserve shared geometry', (
    tester,
  ) async {
    final events = <Map<String, Object>>[];
    await tester.pumpWidget(
      fixture.host(
        Scaffold(
          body: NotationPianoKeyboard(
            data: const {
              'visible': true,
              'enabled': false,
              'quarterTones': false,
              'selectedKeyId': 'C4:',
              'durationPickerOpen': true,
            },
            send: events.add,
          ),
        ),
      ),
    );
    await tester.pumpAndSettle();
    expect(find.byKey(const ValueKey('piano-D4:k')), findsNothing);
    final key = find.byKey(const ValueKey('piano-C4:'));
    expect(tester.getSize(key), const Size(60, 180));
    expect(
      find.byWidgetPredicate(
        (widget) => widget is ColoredBox && (widget.color.a - .18).abs() < .001,
      ),
      findsOneWidget,
    );
    expect(
      (tester.widget<Container>(key).decoration! as BoxDecoration).color,
      Theme.of(tester.element(key)).colorScheme.primary,
    );
    await tester.tap(key);
    expect(events, [
      {'phase': 'dismiss'},
    ]);
    await tester.pumpWidget(
      fixture.host(
        Scaffold(
          body: NotationPianoKeyboard(
            data: const {
              'visible': true,
              'enabled': true,
              'quarterTones': false,
              'selectedKeyId': '',
            },
            send: events.add,
          ),
        ),
      ),
    );
    await tester.pump();
    expect(
      (tester.widget<Container>(key).decoration! as BoxDecoration).color,
      const Color(PianoKeyboardSpec.whiteColor),
    );
    events.clear();
    await tester.pumpWidget(
      fixture.host(
        Scaffold(
          body: NotationPianoKeyboard(
            data: const {'visible': true, 'enabled': false, 'modalShade': .1},
            send: events.add,
          ),
        ),
      ),
    );
    await tester.pump();
    expect(
      find.byWidgetPredicate(
        (widget) => widget is ColoredBox && (widget.color.a - .1).abs() < .001,
      ),
      findsOneWidget,
    );
    await tester.tap(key);
    expect(events, isEmpty);
  });
}
