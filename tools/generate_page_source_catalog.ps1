# Regenerates metadata only. Source contents and credentials are never bundled.
$ErrorActionPreference = 'Stop'
$root = Split-Path $PSScriptRoot -Parent
$classes = [ordered]@{}
$imports = [ordered]@{}
$resources = [ordered]@{}
Get-ChildItem -LiteralPath (Join-Path $root 'lib') -Filter '*.dart' -Recurse | Sort-Object FullName | ForEach-Object {
    $file = $_
    $path = $file.FullName.Substring($root.Length + 1).Replace('\', '/')
    if ($path.EndsWith('page_source_catalog.dart')) { return }
    $source = [IO.File]::ReadAllText($file.FullName)
    foreach ($match in [regex]::Matches($source, '(?m)^\s*(?:(?:abstract|sealed|base|final|interface)\s+)*class\s+(\w+)')) {
        $name = $match.Groups[1].Value
        if (-not $classes.Contains($name)) { $classes[$name] = @() }
        $classes[$name] += $path
    }
    $dependencies = @()
    foreach ($match in [regex]::Matches($source, '(?:import|export|part)\s+[''"]([^''"]+)[''"]')) {
        $uri = $match.Groups[1].Value
        if ($uri.StartsWith('package:sornaz/')) {
            $target = Join-Path (Join-Path $root 'lib') $uri.Substring(15)
        } elseif (-not $uri.Contains(':')) {
            $target = Join-Path $file.DirectoryName $uri
        } else { continue }
        $target = [IO.Path]::GetFullPath($target)
        if ((Test-Path -LiteralPath $target -PathType Leaf) -and $target.StartsWith((Join-Path $root 'lib') + '\')) {
            $dependencies += $target.Substring($root.Length + 1).Replace('\', '/')
        }
    }
    $imports[$path] = @($dependencies | Sort-Object -Unique)
    $assets = @()
    foreach ($match in [regex]::Matches($source, '[''"](assets/[^''"\r\n]+)[''"]')) {
        $asset = $match.Groups[1].Value
        if (Test-Path -LiteralPath (Join-Path $root $asset) -PathType Leaf) {
            $assets += $asset
            if ($asset.EndsWith('.html')) {
                $html = [IO.File]::ReadAllText((Join-Path $root $asset))
                foreach ($ref in [regex]::Matches($html, '(?:src|href)=["'']([^"'']+)["'']')) {
                    $relative = $ref.Groups[1].Value
                    if ($relative.Contains(':')) { continue }
                    $target = [IO.Path]::GetFullPath((Join-Path (Split-Path (Join-Path $root $asset)) $relative))
                    if ($target.StartsWith($root + '\') -and (Test-Path -LiteralPath $target -PathType Leaf)) {
                        $assets += $target.Substring($root.Length + 1).Replace('\', '/')
                    }
                }
            }
        }
    }
    $resources[$path] = @($assets | Sort-Object -Unique)
}
$content = '// Generated by tools/generate_page_source_catalog.ps1. Do not edit.' + "`n" +
    'const pageSourceClasses = <String, List<String>>' + ($classes | ConvertTo-Json -Depth 100) + ";`n" +
    'const pageSourceImports = <String, List<String>>' + ($imports | ConvertTo-Json -Depth 100) + ";`n" +
    'const pageSourceResources = <String, List<String>>' + ($resources | ConvertTo-Json -Depth 100) + ";`n"
[IO.File]::WriteAllText((Join-Path $root 'lib/components/page_source_catalog.dart'), $content, [Text.UTF8Encoding]::new($false))
